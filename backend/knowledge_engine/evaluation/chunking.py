"""Chunking benchmark: the engine's structure and hybrid chunkers against Chonkie's RecursiveChunker
and SemanticChunker, on the same documents, embedding model, size limit and retrieval.

Questions are generated by the local model from pairs of adjacent sentences of the long documents
and kept only if both answer keywords occur verbatim in their sentences, so the gold answer does not
depend on any chunker. Measured per chunker:

- recall@5: a question's keywords are all found in the top 5 passages retrieved (from its document)
- intact@5: one of those passages holds both keywords (the two linked facts stayed together)
- pairs kept together: share of sentence pairs whose two keywords fall in one chunk of the index
- chunks, average size, ingestion time (chunking + embedding, sentence embeddings included)

Retrieval is the engine's hybrid search with the reranker, contextual summaries and second hop off,
so only the chunking differs. Chonkie is an evaluation-only dependency (`evaluation` extra).
"""

import json
import random
import time
from dataclasses import replace
from pathlib import Path
from typing import Any

import httpx
import numpy as np

from knowledge_engine.config import Settings
from knowledge_engine.context import AppContext
from knowledge_engine.evaluation.dataset import load_corpus
from knowledge_engine.evaluation.systems import index_corpus, scratch_context
from knowledge_engine.ingestion.chunker import Chunk, _headings, sentence_spans
from knowledge_engine.llm.ollama import Ollama
from knowledge_engine.pipeline import indexing
from knowledge_engine.retrieval.analyzer import analyze
from knowledge_engine.retrieval.search import retrieve

DELIMITERS = [". ", "! ", "? ", "। ", "॥ ", "۔ ", "؟ ", "\n"]
QUESTION_SCHEMA = {
    "type": "object",
    "properties": {
        "question": {"type": "string", "maxLength": 300},
        "keyword_a": {"type": "string", "maxLength": 60},
        "keyword_b": {"type": "string", "maxLength": 60},
    },
    "required": ["question", "keyword_a", "keyword_b"],
}
QUESTION_PROMPT = """Two consecutive sentences from a document follow. Write ONE question, in the same language as the sentences, whose answer needs a fact from sentence A AND a fact from sentence B (for example who did something and when, or what a scheme is and what it provides). Then copy the key answer words: keyword_a = a short phrase (1-4 words, a name or number when possible) copied EXACTLY from sentence A, keyword_b = a short phrase copied EXACTLY from sentence B. Do not mention "sentence A/B" in the question. Return JSON only.

DOCUMENT: {title}
SENTENCE A: {a}
SENTENCE B: {b}"""


async def _quiet(stage: str, message: str) -> None:
    return None


def pick_pairs(text: str, n: int, rng: random.Random) -> list[tuple[str, str]]:
    """n adjacent sentence pairs inside one section, both of a useful length."""
    spans = sentence_spans(text)
    pairs = []
    for (a0, a1), (b0, b1) in zip(spans, spans[1:], strict=False):
        a, b = text[a0:a1].strip(), text[b0:b1].strip()
        if 60 <= len(a) <= 400 and 60 <= len(b) <= 400 and not b.startswith("#"):
            pairs.append((a, b))
    rng.shuffle(pairs)
    return pairs[:n]


async def make_questions(
    settings: Settings, corpus: dict[str, str], per_doc: int, out: Path
) -> list[dict[str, Any]]:
    if out.exists():
        cached: list[dict[str, Any]] = json.loads(out.read_text())
        return cached
    model, rng, questions = Ollama(settings), random.Random(11), []
    for name, text in corpus.items():
        for a, b in pick_pairs(text, per_doc * 2, rng):
            raw = await model.generate(
                QUESTION_PROMPT.format(title=Path(name).stem, a=a, b=b), QUESTION_SCHEMA, 400
            )
            ka, kb = str(raw.get("keyword_a", "")).strip(), str(raw.get("keyword_b", "")).strip()
            if len(ka) >= 2 and len(kb) >= 2 and ka in a and kb in b and ka not in b:
                questions.append({"doc": name, "question": raw["question"], "a": ka, "b": kb})
            if sum(q["doc"] == name for q in questions) == per_doc:
                break
    out.write_text(json.dumps(questions, ensure_ascii=False, indent=1))
    return questions


def ollama_embeddings(settings: Settings) -> Any:
    """A Chonkie BaseEmbeddings backed by the engine's embedding model (same vectors for all)."""
    from chonkie.embeddings.base import BaseEmbeddings
    from chonkie.tokenizer import CharacterTokenizer

    class _Embeddings(BaseEmbeddings):
        def embed(self, text: str) -> np.ndarray[Any, Any]:
            return self.embed_batch([text])[0]

        def embed_batch(self, texts: list[str]) -> list[np.ndarray[Any, Any]]:
            vectors: list[np.ndarray[Any, Any]] = []
            for i in range(0, len(texts), 32):
                batch = [settings.embedding_document_prefix + t for t in texts[i : i + 32]]
                r = httpx.post(
                    settings.ollama_url + "/api/embed",
                    json={"model": settings.embedding_model, "input": batch, "truncate": True},
                    timeout=settings.model_timeout,
                )
                r.raise_for_status()
                vectors += [np.asarray(v, dtype=np.float32) for v in r.json()["embeddings"]]
            return vectors

        @property
        def dimension(self) -> int:
            return settings.embedding_dimensions

        def get_tokenizer(self) -> Any:
            return CharacterTokenizer()

    return _Embeddings()


def chonkie_chunker(kind: str, settings: Settings) -> Any:
    from chonkie import RecursiveChunker, SemanticChunker
    from chonkie.tokenizer import CharacterTokenizer

    if kind == "chonkie-recursive":
        return RecursiveChunker(tokenizer=CharacterTokenizer(), chunk_size=settings.chunk_chars)
    return SemanticChunker(
        embedding_model=ollama_embeddings(settings),
        chunk_size=settings.chunk_chars,
        delim=DELIMITERS,
    )


def as_chunks(text: str, pieces: list[Any]) -> list[Chunk]:
    """Chonkie chunks -> engine chunks (exact offsets; heading = the section a chunk starts in)."""
    starts, paths, _ = _headings(text)
    chunks: list[Chunk] = []
    for p in pieces:
        s, e = int(p.start_index), int(p.end_index)
        if not text[s:e].strip():
            continue
        k = max((i for i, h in enumerate(starts) if h <= s), default=-1)
        chunks.append(Chunk(len(chunks), text[s:e], s, e, paths[k] if k >= 0 else None))
    return chunks


async def run_variant(
    settings: Settings, kind: str, corpus: dict[str, str], questions: list[dict[str, Any]], k: int
) -> dict[str, Any]:
    scoped = settings.model_copy(
        update={
            "chunker": "hybrid" if kind == "hybrid" else "structure",
            "rerank_model": "",
            "contextual_chunks": False,
            "second_hop": "off",
        }
    )
    original = getattr(indexing, "chunk_document")  # noqa: B009 - swapped for the run
    if kind.startswith("chonkie"):
        chunker = chonkie_chunker(kind, scoped)

        def external(text: str, max_chars: int = 700, **_: Any) -> list[Chunk]:
            return as_chunks(text, chunker.chunk(text))

        setattr(indexing, "chunk_document", external)  # noqa: B010
    try:
        async with scratch_context(scoped) as ctx:
            start = time.perf_counter()
            await index_corpus(ctx, corpus)
            seconds = time.perf_counter() - start
            return await measure(ctx, kind, questions, k, seconds)
    finally:
        setattr(indexing, "chunk_document", original)  # noqa: B010


async def measure(
    ctx: AppContext, kind: str, questions: list[dict[str, Any]], k: int, seconds: float
) -> dict[str, Any]:
    rows = ctx.store.db.rows(
        "SELECT c.text, d.name FROM chunks c JOIN documents d ON d.id=c.document_id"
    )
    by_doc: dict[str, list[str]] = {}
    for r in rows:
        by_doc.setdefault(r["name"], []).append(r["text"])
    together = [
        any(q["a"] in t and q["b"] in t for t in by_doc.get(q["doc"], [])) for q in questions
    ]
    recall, intact = [], []
    for q in questions:
        plan = await analyze(ctx, q["question"], [], _quiet)
        plan.final_k = k
        result = await retrieve(ctx, replace(plan), [], _quiet)
        texts = [
            result.chunks[c.chunk_id]["text"]
            for c in result.selected[:k]
            if result.chunks[c.chunk_id]["document_name"] == q["doc"]
        ]
        recall.append(any(q["a"] in t for t in texts) and any(q["b"] in t for t in texts))
        intact.append(any(q["a"] in t and q["b"] in t for t in texts))
    sizes = [len(r["text"]) for r in rows]
    return {
        "chunker": kind,
        "recall@k": round(sum(recall) / len(recall), 3),
        "intact@k": round(sum(intact) / len(intact), 3),
        "pairs_together": round(sum(together) / len(together), 3),
        "chunks": len(rows),
        "avg_chars": round(sum(sizes) / len(sizes)),
        "ingest_s": round(seconds, 1),
    }


async def benchmark(
    settings: Settings,
    corpus_dirs: list[Path],
    long_docs: Path,
    kinds: list[str],
    k: int,
    work: Path,
) -> list[dict[str, Any]]:
    corpus = load_corpus(corpus_dirs + [long_docs])
    long_corpus = load_corpus([long_docs])
    questions = await make_questions(settings, long_corpus, 4, work / "questions.json")
    print(f"{len(corpus)} documents ({len(long_corpus)} long), {len(questions)} questions")
    results = []
    for kind in kinds:
        result = await run_variant(settings, kind, corpus, questions, k)
        print(json.dumps(result, ensure_ascii=False), flush=True)
        results.append(result)
    return results
